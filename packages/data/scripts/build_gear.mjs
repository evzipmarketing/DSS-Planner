const cameras = [];
function addCamera(id, name, sensor, kind, noise) {
  const [sw, sh, px, py] = sensors[sensor];
  const pixel = (sw / px) * 1000;
  cameras.push({
    id,
    name,
    sensorWidthMm: round(sw),
    sensorHeightMm: round(sh),
    pixelSizeUm: round(pixel),
    widthPx: px,
    heightPx: py,
    sensor: kind,
    readNoiseE: noise,
  });
}

